BEGIN;

-- Existing approval steps have no cycle identifier. Refuse an unsafe migration
-- rather than fabricating workflow history from legacy rows.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM specification_approval_steps) THEN
    RAISE EXCEPTION
      'Cannot apply approval workflow cycle migration: specification_approval_steps contains legacy rows that cannot be mapped safely to an approval cycle.';
  END IF;
END $$;

CREATE TABLE specification_approval_cycles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  specificationid bigint NOT NULL REFERENCES specifications(id) ON DELETE CASCADE,
  cycleno integer NOT NULL CHECK (cycleno > 0),
  approvalpatternid bigint REFERENCES approval_patterns(id),
  approvalpatternno smallint,
  approvalpatternname varchar(150),
  status varchar(30) NOT NULL,
  submittedbyuserid varchar(255),
  submittedbydisplayname varchar(150),
  submittedat timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  completedat timestamp without time zone,
  closedreason text,
  created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_specification_approval_cycle UNIQUE (specificationid, cycleno),
  CONSTRAINT chk_specification_approval_cycle_status
    CHECK (status IN ('Active', 'Completed', 'Returned', 'Rejected'))
);

CREATE INDEX idx_specification_approval_cycles_specificationid
  ON specification_approval_cycles (specificationid);

CREATE UNIQUE INDEX uq_specification_approval_cycles_active_specification
  ON specification_approval_cycles (specificationid)
  WHERE status = 'Active';

ALTER TABLE specification_approval_steps
  ADD COLUMN approvalcycleid bigint,
  ADD COLUMN assignedapproveruserid varchar(255),
  ADD COLUMN actionbyuserid varchar(255);

ALTER TABLE specification_approval_steps
  ADD CONSTRAINT specification_approval_steps_approvalcycleid_fkey
  FOREIGN KEY (approvalcycleid)
  REFERENCES specification_approval_cycles(id)
  ON DELETE CASCADE;

ALTER TABLE specification_approval_steps
  DROP CONSTRAINT uq_specification_approval_step;

ALTER TABLE specification_approval_steps
  ADD CONSTRAINT uq_specification_approval_cycle_step
  UNIQUE (approvalcycleid, stepno);

ALTER TABLE specification_approval_steps
  ADD CONSTRAINT chk_specification_approval_steps_status
  CHECK (approvalstatus IN ('Pending', 'Approved', 'Returned', 'Rejected', 'Cancelled'));

CREATE INDEX idx_specification_approval_steps_approvalcycleid
  ON specification_approval_steps (approvalcycleid);

CREATE INDEX idx_specification_approval_steps_assigned_pending
  ON specification_approval_steps (assignedapproveruserid)
  WHERE approvalstatus = 'Pending';

ALTER TABLE specification_status_history
  ADD COLUMN changedbyuserid varchar(255);

CREATE TABLE specification_approval_step_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  specificationid bigint NOT NULL REFERENCES specifications(id) ON DELETE CASCADE,
  approvalcycleid bigint NOT NULL REFERENCES specification_approval_cycles(id) ON DELETE CASCADE,
  approvalstepid bigint NOT NULL REFERENCES specification_approval_steps(id) ON DELETE CASCADE,
  assignedapproveruserid varchar(255),
  actoruserid varchar(255),
  actordisplayname varchar(150),
  actorrole varchar(100),
  eventtype varchar(30) NOT NULL,
  previousstepstatus varchar(30),
  newstepstatus varchar(30) NOT NULL,
  comments text,
  occurredat timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT chk_specification_approval_step_events_type
    CHECK (eventtype IN ('Approved', 'Returned', 'Rejected', 'Cancelled')),
  CONSTRAINT chk_specification_approval_step_events_status
    CHECK (newstepstatus IN ('Approved', 'Returned', 'Rejected', 'Cancelled'))
);

CREATE INDEX idx_specification_approval_step_events_specificationid
  ON specification_approval_step_events (specificationid);

CREATE INDEX idx_specification_approval_step_events_approvalcycleid
  ON specification_approval_step_events (approvalcycleid);

CREATE INDEX idx_specification_approval_step_events_approvalstepid
  ON specification_approval_step_events (approvalstepid);

-- A composite FK prevents a step from referencing a cycle for another specification.
ALTER TABLE specification_approval_cycles
  ADD CONSTRAINT uq_specification_approval_cycle_id_specification
  UNIQUE (id, specificationid);

ALTER TABLE specification_approval_steps
  ADD CONSTRAINT specification_approval_steps_cycle_specification_fkey
  FOREIGN KEY (approvalcycleid, specificationid)
  REFERENCES specification_approval_cycles (id, specificationid);

COMMIT;
